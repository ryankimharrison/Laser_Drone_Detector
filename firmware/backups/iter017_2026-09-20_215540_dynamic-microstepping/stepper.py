class VelocityLoop:
    """
    The 200 Hz loop that makes velocity mode a mode rather than a command.

    Everything here exists because a tracking turret must never stop. The host
    sends a RATE, this holds it, and motion is continuous between commands --
    as opposed to `aim`, which accelerates from rest, arrives, and decelerates
    to a standstill every single time. Measured on this hardware, a 4.7 deg
    `aim` costs 164-325 ms of which ~139 ms is the ramp up and back down, so
    commanding position at frame rate yields a few discrete hops per second.
    That is the "jumping to where the mouse is" failure exactly.

    THE WATCHDOG IS NOT OPTIONAL. In move mode a lost USB link means a move
    finishes and the motors stop. In velocity mode it means a motor holds its
    last rate forever. So a tick with no recent `vel` ramps the target to zero
    and cuts the laser by direct GPIO write -- not through the CLI, which may
    be exactly what is wedged.
    """

    def __init__(self, axes, laser_pin=None):
        self.axes = axes
        # Bound to plain attributes because the ISR must not iterate: a dict
        # view and its iterator are two allocations per tick, and the ISR has
        # no allocator. Two motors, two attributes, no loop.
        self._a = axes["pan"]
        self._b = axes["tilt"]
        self.laser_pin = laser_pin
        self.timer = None
        self._dt_us = config.VEL_TICK_MS * 1000
        self._last_cmd_ms = 0
        self._tripped = False
        self.ticks = 0
        self.trips = 0
        self._limited = False
        self._pitch_sum_limit = 0
        # --- IMU crash guard, published from ordinary context -------------
        # PLAIN BOOLEANS, and they must stay that way. The ISR reads these;
        # it cannot call into guard.py, because a decision needs an I2C
        # transaction and an I2C transaction allocates and can raise. So the
        # measuring happens on the command path (see apply_guard) and the ISR
        # does nothing but compare a sign and zero a rate.
        self._blk_pos = False      # refuse a pitch push > 0
        self._blk_neg = False      # refuse a pitch push < 0
        self._blk_all = False      # impact latched: refuse everything
        self._guard_stops = 0
        self._guard_hit = False
        #: Step-sum reading at the last start(), so the pitch clamp's frame is
        #: centred on the pose tracking STARTED from rather than on whatever
        #: `position` homing happened to leave behind. See start().
        self._tot0 = 0
        self.shifts = 0
        self._shift_pending = 0
        self._shift_deferred_out = 0
        self._gear_request = 16
        self._gear_request_ms = 0
        self._last_shift_ms = -500
        self.gear_capped = False

    # ------------------------------------------------------------------
    def start(self):
        if self.timer is not None:
            return
        self._a.enter_vel_mode()
        self._b.enter_vel_mode()
        self._last_cmd_ms = time.ticks_ms()
        self._tripped = False
        # `limited` is a latch so a host that polls slowly still sees that the
        # clamp fired. Clear it HERE so it means "during this tracking run"
        # rather than "at some point since the board booted" -- otherwise the
        # first run that clamps makes every later run report limited.
        self._limited = False
        # The crash guard's LATCH is likewise per-run, for the same reason:
        # it is evidence about this run. The block flags themselves are NOT
        # cleared here -- they are a live measurement of where the payload is
        # right now, and starting velocity mode does not move it. Clearing
        # them would hand back a full-speed gate to a payload sitting against
        # its frame.
        self._guard_hit = False
        # CENTRE THE CLAMP ON THE POSE WE ARE STARTING FROM.
        #
        # _arm_pitch_limit's docstring says the frame is centred on the placed
        # pose, but _tick compared the RAW sum, and vel_position is
        # `position + _pos_micro // 1e6` -- `position` being the position-mode
        # counter left over from homing, which enter_vel_mode does not reset
        # (it resets only _pos_micro). Taking the reading here makes the frame
        # mean what it claims.
        # Fixed 1/16 units: a gear change must not move the travel-limit datum.
        self._tot0 = ((self._a.vel_position + self._b.vel_position) * 16
                      // self._a.microstep)
        self._gear_request = self._a.microstep
        self._gear_request_ms = time.ticks_ms()
        self._last_shift_ms = time.ticks_ms() - 500
        self._arm_pitch_limit()
        self.timer = Timer()
        self.timer.init(period=config.VEL_TICK_MS,
                        mode=Timer.PERIODIC, callback=self._tick)

    def _arm_pitch_limit(self):
        """
        Precompute the pitch travel limit as an integer step sum.

        `vel` and `pvel` are RATE commands, so nothing in the move path's
        limit checking applies to them -- the firmware would happily drive the
        payload through the yoke at a steady 400 steps/s. The limit has to be
        enforced here, in the only code that sees every tick.

        For a differential, pitch is proportional to the SUM of the two motor
        positions (and yaw to their difference), so the whole check reduces to
        one integer comparison against a precomputed bound. Computed once per
        start() because it depends on microstepping.
        """
        lim = config.PAYLOAD_LIMIT_DEG.get("pitch")
        if not lim:
            self._pitch_sum_limit = 0          # 0 == no limit
            return
        ms = 16  # travel-limit comparison and datum stay in canonical units
        motor_step_deg = 360.0 / (config.FULL_STEPS_PER_REV * ms)
        bound = max(abs(lim[0]), abs(lim[1]))
        self._pitch_sum_limit = int(
            bound * 2.0 * config.DIFFERENTIAL_N / motor_step_deg)

    def stop(self):
        if self.timer is not None:
            self.timer.deinit()
            self.timer = None
        dynamic = getattr(config, "VEL_CANONICAL16", False)
        if dynamic:
            # Preserve sub-coarse-step fractions before leave_vel_mode folds
            # them into an integer. Otherwise stopping in 1/8 loses fine steps.
            pa16 = ((self._a.position * 1000000 + self._a._pos_micro) * 16
                    // self._a.microstep // 1000000)
            pb16 = ((self._b.position * 1000000 + self._b._pos_micro) * 16
                    // self._b.microstep // 1000000)
        self._a.leave_vel_mode()
        self._b.leave_vel_mode()
        if dynamic:
            # Position commands, homing and the end-of-run rewind use fine
            # units. Returning to finer steps needs no phase alignment.
            self._a.set_microstep(16)
            self._b.set_microstep(16)
            self._a.position, self._b.position = pa16, pb16
            self._arm_pitch_limit()

    @property
    def running(self):
        return self.timer is not None

    # ------------------------------------------------------------------
    def command(self, rate_a, rate_b):
        """Set both motor rates and pet the watchdog."""
        if not self.running:
            self.start()
        # Shift first, then convert the request into the units the shift just
        # created. A rate arrives expressed in the CURRENT microstep, and a
        # shift changes what a step is worth -- applying an old-units rate
        # after a 16->4 shift commands four times the intended speed. The
        # first version of this did exactly that and drove straight through
        # the travel limit.
        before = self._a.microstep
        self._maybe_shift(rate_a, rate_b)
        after = self._a.microstep
        if after != before:
            rate_a = rate_a * after / before
            rate_b = rate_b * after / before
        self.gear_capped = False
        if getattr(config, "VEL_CANONICAL16", False):
            peak = max(abs(rate_a), abs(rate_b))
            limit = config.VEL_DYNAMIC_PULSE_LIMIT
            if peak > limit:
                factor = limit / peak
                rate_a *= factor
                rate_b *= factor
                self.gear_capped = True
        self._a.set_target_rate(rate_a)
        self._b.set_target_rate(rate_b)
        self._last_cmd_ms = time.ticks_ms()
        self._tripped = False

    # ------------------------------------------------------------------
    def _gear_for(self, payload_dps):
        """Divisor for a payload speed, with hysteresis about the current one."""
        cur = self._a.microstep
        h = config.VEL_GEAR_HYSTERESIS
        pick = config.VEL_GEARS[-1][1]
        for thresh, div in config.VEL_GEARS:
            # Widen the band we are already in, so speeds hovering on a
            # boundary do not shift back and forth every command.
            t = thresh * (1.0 + h) if div == cur else thresh
            if payload_dps <= t:
                pick = div
                break
        return pick

    def _maybe_shift(self, rate_a, rate_b):
        """
        Change microstepping to suit the commanded speed.

        Called from the command path, never the ISR: a shift means touching
        three GPIOs per driver, a settle delay and a rescale of both step
        counters, none of which belongs in an interrupt.
        """
        if not getattr(config, "VEL_GEARSHIFT", False):
            return
        if getattr(config, "VEL_CANONICAL16", False):
            self._maybe_shift_dynamic(rate_a, rate_b)
            return
        cur = self._a.microstep
        if self._b.microstep != cur:
            return                     # mismatched; kinematics will complain
        # Payload speed from the two motor rates: pitch and yaw are the sum
        # and difference, and the faster of the two is what has to be served.
        deg_per_step = 360.0 / (config.FULL_STEPS_PER_REV * cur
                                * config.DIFFERENTIAL_N)
        pitch_dps = abs(rate_a + rate_b) * deg_per_step / 2.0
        yaw_dps = abs(rate_a - rate_b) * deg_per_step / 2.0
        want = self._gear_for(pitch_dps if pitch_dps > yaw_dps else yaw_dps)
        if want == cur:
            self._shift_pending = 0
            return

        # Only shift where the counts line up exactly.
        #
        # An A4988 jumps its internal indexer to the nearest state in the new
        # table when MSx changes, so shifting off an unaligned count moves the
        # motor by up to one fine step -- physically, silently, and with
        # nothing to detect it because this platform has no encoder. Landing
        # on a count that is valid in BOTH tables makes the shift exact.
        # Coarse->fine is always safe: every coarse translator state is also a
        # valid fine state, so no alignment is needed in that direction.
        if cur > want:
            ratio16 = 16 // want
            if (self._a.phase16 % ratio16) or (self._b.phase16 % ratio16):
                # Unaligned. If nothing is turning the phase will never
                # advance, so waiting is pointless and forcing would cost a
                # step for no gain -- just stay in the finer gear.
                if self._a.current_rate == 0 and self._b.current_rate == 0:
                    return
                # Not aligned yet. It will be within a few steps; defer.
                # Alignment comes round every `ratio16` sixteenth-steps, so
                # at any real rate this resolves within milliseconds. The
                # counter only exists so a pathological case cannot wedge the
                # gear forever.
                self._shift_pending += 1
                if self._shift_pending < 60:
                    return
                self._shift_deferred_out += 1
        self._shift_pending = 0
        self._do_shift(want)

    def _maybe_shift_dynamic(self, rate_a, rate_b):
        """Two gears, separated thresholds and dwell; never force alignment."""
        cur = self._a.microstep
        if cur != self._b.microstep or cur not in (8, 16):
            raise StepperUsageError("dynamic profile requires paired 1/8 or 1/16")
        demand16 = max(abs(rate_a), abs(rate_b)) * 16 / cur
        actual16 = max(abs(self._a.current_rate), abs(self._b.current_rate)) * 16 / cur
        fine_cap = config.VEL_DYNAMIC_PULSE_LIMIT
        want = cur
        if cur == 16 and demand16 > .70 * fine_cap:
            want = 8
        elif cur == 8 and max(demand16, actual16) < .40 * fine_cap:
            want = 16
        now = time.ticks_ms()
        if want != self._gear_request:
            self._gear_request = want
            self._gear_request_ms = now
        if want == cur or time.ticks_diff(now, self._last_shift_ms) < 500:
            return
        dwell = 100 if want == 8 else 300
        if time.ticks_diff(now, self._gear_request_ms) < dwell:
            return
        if want == 8 and (self._a.phase16 % 2 or self._b.phase16 % 2):
            self._shift_deferred_out += 1
            return
        if self._do_shift(want):
            self._last_shift_ms = now

    def _do_shift(self, div):
        """Exclude the ISR while changing paired units and driver pins.

        phase16 is the existing dead-reckoned phase, NOT a hardware pulse
        counter. Physical phase continuity must still be checked on the rig.
        """
        a, b = self._a, self._b
        irq = machine.disable_irq()
        try:
            old = a.microstep
            if div < old and (a.phase16 % (16 // div) or b.phase16 % (16 // div)):
                return False
            a.vel_sm.active(0)
            b.vel_sm.active(0)
            # Let any high pulse meet the driver minimum before parking low.
            time.sleep_us(5)
            a.vel_sm.exec(_VEL_SET_LOW)
            b.vel_sm.exec(_VEL_SET_LOW)
            a._set_period(0)
            b._set_period(0)
            for ax in (a, b):
                total = (ax.position * 1000000 + ax._pos_micro) * div // old
                ax.set_microstep(div)
                # Do not independently truncate the base and accumulated
                # fraction: repeated 16->8->16 shifts would walk the datum.
                ax.position = total // 1000000
                ax._pos_micro = total - ax.position * 1000000
                ax._set_period(ax._period_for(abs(ax.current_rate)))
            self._arm_pitch_limit()
            a.vel_sm.active(1)
            b.vel_sm.active(1)
            self.shifts += 1
            return True
        except Exception:
            # Leave both generators parked if only part of a shift succeeded.
            a.vel_sm.active(0)
            b.vel_sm.active(0)
            a.target_rate = b.target_rate = 0
            a.current_rate = b.current_rate = 0
            if self.laser_pin is not None:
                self.laser_pin.value(0)
            raise
        finally:
            machine.enable_irq(irq)

    def apply_guard(self, guard):
        """Publish a CrashGuard's decision to the ISR. ORDINARY CONTEXT ONLY.

        Called from the `vel`/`pvel` command path immediately after the guard
        has sampled, so the flags the ISR sees are never more than one host
        command old. Copying them onto plain attributes here -- rather than
        letting the ISR reach into the guard object -- keeps the interrupt
        free of attribute chains on an object that may be None, mid-update, or
        holding a half-written float.
        """
        if guard is None:
            self._blk_pos = self._blk_neg = self._blk_all = False
            return
        self._blk_pos = bool(guard.block_pos)
        self._blk_neg = bool(guard.block_neg)
        self._blk_all = bool(guard.impact)

    def age_ms(self):
        return time.ticks_diff(time.ticks_ms(), self._last_cmd_ms)

    @property
    def tripped(self):
        return self._tripped

    @property
    def limited(self):
        return self._limited

    @property
    def guard_hit(self):
        """True if the IMU crash guard stopped the payload during this run."""
        return self._guard_hit

    @property
    def guard_stops(self):
        return self._guard_stops

    # ------------------------------------------------------------------
    def _tick(self, _t):
        # INTERRUPT CONTEXT. No allocation, no iteration, no formatting, and
        # nothing that can raise -- an exception here leaves a motor running.
        self.ticks += 1
        if time.ticks_diff(time.ticks_ms(),
                           self._last_cmd_ms) > config.VEL_WATCHDOG_MS:
            if not self._tripped:
                self._tripped = True
                self.trips += 1
                if self.laser_pin is not None:
                    self.laser_pin.value(0)
            self._a.target_rate = 0
            self._b.target_rate = 0
        # Pitch travel limit. Pitch is the SUM of the motor positions, yaw the
        # difference, so when the sum is at its bound the fix is to strip the
        # pitch component out of the command and keep the yaw component --
        # the payload stops tilting but can still turn, and can always move
        # back off the stop.
        lim = self._pitch_sum_limit
        if lim:
            tot = ((self._a.vel_position + self._b.vel_position) * 16
                   // self._a.microstep) - self._tot0
            if tot > lim or tot < -lim:
                ta = self._a.target_rate
                tb = self._b.target_rate
                push = ta + tb
                if (tot > 0 and push > 0) or (tot < 0 and push < 0):
                    # STOP, do not steer.
                    #
                    # This used to keep (ta - tb) // 2 and call it "the yaw
                    # component". When the demand is nearly PURE PITCH that
                    # residual is noise, and executing it is a yaw slew
                    # nobody asked for. Measured on run_2026-09-20_132627:
                    # the loop asked for (-319, -514) and the clamp executed
                    # (+97, -97) -- 4.75 deg/s of yaw -- which moved the
                    # drone's box 270 px AWAY from the goal and took the
                    # pixel error from 145 to 360. It reads exactly like a
                    # motor running backwards, and it is not.
                    #
                    # Zeroing both is the only response that cannot move the
                    # payload in a direction the control law never asked
                    # for. Coming back off the stop still works: the next
                    # command whose push has the opposite sign fails the
                    # test above and passes through untouched.
                    self._a.target_rate = 0
                    self._b.target_rate = 0
                    self._limited = True

        # IMU CRASH GUARD. The clamp above is dead reckoning: it counts steps
        # and believes them, which is exactly what stops being true when the
        # payload hits something. This one is the same shape of check against
        # a number that came from gravity -- see guard.py.
        #
        # Same response as the clamp, and for the same reason: ZERO BOTH, do
        # not steer. Keeping a "yaw component" of a refused pitch demand is
        # what drove the drone's box 270 px the wrong way on run_132627.
        if self._blk_all:
            self._a.target_rate = 0
            self._b.target_rate = 0
            if not self._guard_hit:
                self._guard_hit = True
                self._guard_stops += 1
            if self.laser_pin is not None:
                self.laser_pin.value(0)
        elif self._blk_pos or self._blk_neg:
            push = self._a.target_rate + self._b.target_rate
            if (push > 0 and self._blk_pos) or (push < 0 and self._blk_neg):
                self._a.target_rate = 0
                self._b.target_rate = 0
                if not self._guard_hit:
                    self._guard_hit = True
                    self._guard_stops += 1
        dt = self._dt_us
        self._a.vel_tick(dt)
        self._b.vel_tick(dt)


def build_axes():
    """Create both axes.  Pan uses PIO0 sm0, tilt uses PIO1 sm0."""
    return {
        "pan": Axis(pinmap.PAN, 0),
        "tilt": Axis(pinmap.TILT, 4),
    }
