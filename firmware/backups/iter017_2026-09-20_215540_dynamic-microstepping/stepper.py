# --------------------------------------------------------------------------


def _profile_time_fn(n, v_max, v_min, a):
    """
    Build t(s): the time at which the profile reaches step position `s`.

    Returns a closure over a trapezoidal profile spanning `n` steps. Working
    in *time* rather than per-step rates is what lets two motors share one
    timeline exactly -- scaling two rate profiles independently makes their
    ramp step-counts round differently, and they then finish a few percent
    apart, which shows up as a dogleg at the end of a combined move.
    """
    v_max = max(1e-6, v_max)
    v_min = max(1e-6, min(v_min, v_max))
    if a > 0:
        ramp = int((v_max * v_max - v_min * v_min) / (2.0 * a))
    else:
        ramp = 0
    ramp = max(0, ramp)
    if 2 * ramp > n:
        ramp = n // 2
    cruise = n - 2 * ramp
    vmin_sq = v_min * v_min

    if ramp:
        v_peak = (vmin_sq + 2.0 * a * ramp) ** 0.5
        t_ramp = (v_peak - v_min) / a
    else:
        v_peak = v_min
        t_ramp = 0.0
    t_cruise_end = t_ramp + cruise / v_peak
    t_total = t_cruise_end + t_ramp

    def t_at(s):
        if s <= 0.0:
            return 0.0
        if s >= n:
            return t_total
        if ramp and s <= ramp:
            return ((vmin_sq + 2.0 * a * s) ** 0.5 - v_min) / a
        if s <= ramp + cruise:
            return t_ramp + (s - ramp) / v_peak
        d = n - s                      # steps still to go, mirror of the ramp
        return t_total - ((vmin_sq + 2.0 * a * d) ** 0.5 - v_min) / a

    return t_at


def _sync_delays(n_self, n_dom, t_at):
    """
    Yield the gap in seconds between consecutive steps for one motor.

    `t_at` is the shared timeline defined over `n_dom` dominant-axis steps.
    A motor taking `n_self` steps places its j-th step at path fraction
    j/n_self, i.e. at dominant position j*n_dom/n_self. Both motors read the
    same clock, so they cannot drift apart.
    """
    if n_self <= 0:
        return
    scale = float(n_dom) / n_self
    prev = 0.0
    for j in range(1, n_self + 1):
        t = t_at(j * scale)
        dt = t - prev
        prev = t
        yield dt if dt > 1e-9 else 1e-9


def coordinated_move(axis_a, axis_b, steps_a, steps_b, rate=None, accel=None,
                     start_rate=None, guard=None, on_progress=None):
    """
    Move both motors at once, starting and finishing together.

    This is what the differential needs. Running one axis and then the other
    would trace an L-shaped path through (pitch, yaw) -- the payload would
    swing out and come back instead of going straight there. Both motors are
    fed from a single loop, and the shorter move's profile is time-scaled so
    the two finish on the same tick.

    `rate` / `start_rate` / `accel` apply to the DOMINANT motor (the one with
    more steps); the other is scaled down in proportion.
    """
    if not (axis_a.enabled and axis_b.enabled):
        raise StepperError("both motors must be enabled for a coordinated move")

    # THE GUARD move() AND single_step() BOTH HAVE AND THIS DID NOT.
    #
    # Two step generators share one STEP pin per axis. Running a coordinated
    # move while an axis is in velocity mode has both writing the same pad,
    # and -- worse -- the finally clause below calls _release_step_pin() on
    # both axes, handing the pad to SIO while the velocity SM is still
    # active and still being fed periods. The axis then counts steps it
    # never emits until the next reboot.
    for ax in (axis_a, axis_b):
        if ax.mode == "vel":
            # StepperUsageError, not StepperError -- see the same guard in
            # Axis.move(). A refused move must not de-energise a loaded axis.
            raise StepperUsageError(
                "%s is in velocity mode -- 'velmode off' before moving"
                % ax.name)

    na, nb = int(steps_a), int(steps_b)
    fwd_a, fwd_b = na > 0, nb > 0
    aa, ab = abs(na), abs(nb)
    n_max = max(aa, ab)

    if n_max == 0:
        return {"steps_a": 0, "steps_b": 0, "aborted": False,
                "guarded": False, "elapsed_us": 0, "requested": (na, nb)}

    v_max = float(rate if rate is not None
                  else config.MAX_RATE.get(axis_a.name, 2000))
    v_min = float(start_rate if start_rate is not None
                  else config.START_RATE.get(axis_a.name, 200))
    acc = float(accel if accel is not None
                else config.ACCEL.get(axis_a.name, 20000))
    v_max = max(1.0, min(v_max, config.ABSOLUTE_MAX_RATE))
    v_min = max(1.0, min(v_min, v_max))

    # One timeline, defined over the dominant axis; both motors sample it.
    t_at = _profile_time_fn(n_max, v_max, v_min, acc)
    gen_a = _sync_delays(aa, n_max, t_at)
    gen_b = _sync_delays(ab, n_max, t_at)

    axis_a.set_direction(fwd_a)
    axis_b.set_direction(fwd_b)
    axis_a._abort = False
    axis_b._abort = False

    for ax in (axis_a, axis_b):
        ax.sm.active(0)
        _clear_fifos(ax.sm_id)
        ax.sm.restart()
        ax._claim_step_pin()
        ax.sm.active(1)

    if n_max >= _GC_THRESHOLD_STEPS:
        gc.collect()

    done_a = done_b = 0
    fed_a = fed_b = False if aa or ab else True
    end_a = aa == 0
    end_b = ab == 0
    guarded = False
    t0 = time.ticks_us()

    try:
        while not (end_a and end_b):
            moved = False
            if not end_a and axis_a.sm.tx_fifo() < 4:
                try:
                    axis_a.sm.put(axis_a._delay_word(1.0 / next(gen_a)))
                    done_a += 1
                    moved = True
                except StopIteration:
                    end_a = True
            if not end_b and axis_b.sm.tx_fifo() < 4:
                try:
                    axis_b.sm.put(axis_b._delay_word(1.0 / next(gen_b)))
                    done_b += 1
                    moved = True
                except StopIteration:
                    end_b = True

            if ((done_a + done_b) & 63) == 0 or not moved:
                if on_progress:
                    on_progress(done_a + done_b, aa + ab)
                if axis_a._abort or axis_b._abort:
                    raise _Stop()
                if guard is not None and guard():
                    guarded = True
                    raise _Stop()

        while axis_a.sm.tx_fifo() > 0 or axis_b.sm.tx_fifo() > 0:
            if guard is not None and guard():
                guarded = True
                break
        tail = ((axis_a._delay_word(v_min) + _PIO_OVERHEAD_CYCLES)
                * 1000000 // config.PIO_CLOCK_HZ)
        time.sleep_us(min(tail + 50, 50000))

    except _Stop:
        pass
    finally:
        left_a = left_b = 0
        for ax in (axis_a, axis_b):
            ax.sm.active(0)
        left_a = axis_a.sm.tx_fifo()
        left_b = axis_b.sm.tx_fifo()
        for ax in (axis_a, axis_b):
            _clear_fifos(ax.sm_id)
            ax._release_step_pin()
        emit_a = done_a - left_a
        emit_b = done_b - left_b
        axis_a.position += emit_a if fwd_a else -emit_a
        axis_b.position += emit_b if fwd_b else -emit_b

    return {
        "steps_a": emit_a if fwd_a else -emit_a,
        "steps_b": emit_b if fwd_b else -emit_b,
        "requested": (na, nb),
        "aborted": axis_a._abort or axis_b._abort,
        "guarded": guarded,
        "elapsed_us": time.ticks_diff(time.ticks_us(), t0),
        "peak_rate": v_max,
    }


