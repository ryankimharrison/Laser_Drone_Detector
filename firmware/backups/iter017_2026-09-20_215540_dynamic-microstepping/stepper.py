"""
Stepper axis driver for the Laser Turret board.

Step pulses are generated by an RP2040 PIO state machine, one per axis
(pan on PIO0, tilt on PIO1), so pulse timing is hardware-exact and immune
to MicroPython's garbage collector.  The CPU only feeds a per-step delay
word into the TX FIFO; the FIFO provides the buffering that lets a
trapezoidal acceleration profile stream out smoothly.

Supports both A4988 and DRV8825 carriers -- the microstep truth tables
differ and picking the wrong one silently changes your step count.
"""

import gc
import time

import machine
import rp2
from machine import Pin, Timer

import config
import pinmap

# --------------------------------------------------------------------------
# Microstep truth tables.  (m0, m1, m2) -> divisor.
#
# These are NOT the same chip to chip.  Note 1/16 in particular:
#   A4988   1/16 = MS1,MS2,MS3 = 1,1,1
#   DRV8825 1/16 = M0,M1,M2    = 0,0,1
# Wiring them from the wrong table is a classic source of "my motor turns
# exactly half as far as I asked".
# --------------------------------------------------------------------------
MICROSTEP_TABLE = {
    "A4988": {
        1:  (0, 0, 0),
        2:  (1, 0, 0),
        4:  (0, 1, 0),
        8:  (1, 1, 0),
        16: (1, 1, 1),
    },
    "DRV8825": {
        1:  (0, 0, 0),
        2:  (1, 0, 0),
        4:  (0, 1, 0),
        8:  (1, 1, 0),
        16: (0, 0, 1),
        32: (1, 0, 1),
    },
}

# PIO program overhead, in state-machine cycles, per step.  Derived from the
# instruction count below: out=1, set hi=1+7 delay, set lo=1, loop=x+1.
_PIO_OVERHEAD_CYCLES = 11

# Moves shorter than this skip the pre-move gc.collect().  Measured on a Pico
# at 125 MHz: collect() is ~1.7 ms, and total fixed overhead per move() is
# ~3.5 ms, so collecting before a 10-step move costs more than the move.
_GC_THRESHOLD_STEPS = 256


@rp2.asm_pio(set_init=rp2.PIO.OUT_LOW, autopull=True, pull_thresh=32)
def _step_program():
    """One FIFO word per step; the word is the extra delay in PIO cycles."""
    wrap_target()
    out(x, 32)              # fetch this step's delay
    set(pins, 1)      [7]   # STEP high for 8 cycles (A4988 needs >=1 us)
    set(pins, 0)            # STEP low
    label("hold")
    jmp(x_dec, "hold")      # burn x+1 cycles to set the period
    wrap()


@rp2.asm_pio(set_init=rp2.PIO.OUT_LOW)
def _vel_program():
    """
    Free-running step generator: one FIFO word sets the PERIOD, and it sticks.

    The move program takes one word per step, which is right for a move of
    known length and useless for tracking -- the CPU would have to feed it
    forever. Here the period lives in X and survives, so the state machine
    keeps stepping at the last commanded rate with no CPU involvement at all.

    The trick is `pull(noblock)`: on an empty FIFO it copies X into OSR
    (RP2040 datasheet 3.4.7) rather than stalling, so `mov(x, osr)` just puts
    the same period back. Write a new word and the next iteration picks it up.

    Cycles per step = 15 + Y, so period = clock / rate and Y = period - 15.
    A period of 0 means idle: no pulses, but the machine keeps polling, so it
    resumes the instant a rate arrives.
    """
    label("top")
    pull(noblock)            # empty FIFO -> OSR = X, so the period persists
    mov(x, osr)
    jmp(not_x, "top")        # 0 == idle
    mov(y, x)                # Y is the countdown; X must survive it
    set(pins, 1)    [7]      # STEP high 8 cycles (A4988 needs >= 1 us)
    set(pins, 0)
    label("hold")
    jmp(y_dec, "hold")
    jmp("top")


# The two instructions the velocity loop executes from the CPU side, encoded
# ONCE at import.
#
# sm.exec("pull(noblock)") looks harmless and is not: it assembles that string
# on every single call. At 200 Hz x 2 axes that is 400 parses a second inside
# an interrupt handler, where MicroPython cannot run the allocator at all.
# Encoding to an int up front makes the ISR path a plain register write.
try:
    _VEL_PULL = rp2.asm_pio_encode("pull(noblock)", 0)
    _VEL_MOV_X_OSR = rp2.asm_pio_encode("mov(x, osr)", 0)
    _VEL_SET_LOW = rp2.asm_pio_encode("set(pins, 0)", 0)
except (AttributeError, NotImplementedError):
    # Host-side fakes do not implement the encoder; the strings are only ever
    # used off-board, where allocation is fine.
    _VEL_PULL = "pull(noblock)"
    _VEL_MOV_X_OSR = "mov(x, osr)"
    _VEL_SET_LOW = "set(pins, 0)"


class StepperError(Exception):
    """A real fault: the hardware is in a state that cannot be driven."""
    usage = False


class StepperUsageError(StepperError):
    """
    A bad argument, not a hardware fault.

    Callers distinguish it by the `usage` flag rather than by catching a
    second base class: MicroPython cannot build an exception from two
    built-in bases with different instance layouts, so the obvious
    `(StepperError, ValueError)` raises "multiple bases have instance
    lay-out conflict" at import time on the Pico even though CPython
    accepts it.

    The CLI keys off this flag to avoid de-energising the motors just
    because someone typed an unsupported microstep ratio -- on a tilt axis
    with gravity on it, dropping holding torque over a typo drops the barrel.
    """
    usage = True


class Axis:
    """One stepper axis: driver control pins plus a PIO step generator."""

    def __init__(self, spec, sm_id):
        self.spec = spec
        self.name = spec["name"]
        self.ref = spec["ref"]

        self.step_pin = Pin(spec["step"], Pin.OUT, value=0)
        self.dir_pin = Pin(spec["dir"], Pin.OUT, value=0)
        # Driver EN is active LOW.  Start HIGH == disabled == coils released.
        self.en_pin = Pin(spec["en"], Pin.OUT, value=1)
        self.m_pins = (
            Pin(spec["m0"], Pin.OUT, value=0),
            Pin(spec["m1"], Pin.OUT, value=0),
            Pin(spec["m2"], Pin.OUT, value=0),
        )

        self._init_pad2(spec["fault"])

        self.position = 0          # in microsteps, signed
        self.microstep = 1
        self._enabled = False
        self._abort = False
        self._last_move = {}

        self.sm_id = sm_id
        self.sm = rp2.StateMachine(
            sm_id,
            _step_program,
            freq=config.PIO_CLOCK_HZ,
            set_base=self.step_pin,
        )

        # Velocity mode runs on a SECOND state machine sharing the same STEP
        # pin. Two machines rather than one reprogrammed machine because
        # swapping a PIO program at runtime means re-uploading instructions
        # and re-deriving the pin mapping every time the mode changes; keeping
        # both resident costs two SMs and makes mode switching a pair of
        # active() calls that cannot half-fail.
        self.mode = "idle"                 # "idle" | "move" | "vel"
        self.vel_sm_id = sm_id + config.VEL_SM_OFFSET
        self.vel_sm = rp2.StateMachine(
            self.vel_sm_id,
            _vel_program,
            freq=config.VEL_PIO_CLOCK_HZ,
            set_base=self.step_pin,
        )
        self.vel_sm.active(0)
        self.target_rate = 0               # signed microsteps/s, INT
        self.current_rate = 0              # signed, after accel limiting, INT
        # DIRECTION CACHE FOR VELOCITY MODE. vel_tick() writes the DIR pin only
        # when the sign it wants differs from this, so this MUST always equal
        # what the pin physically says, or a motor runs the wrong way and
        # nothing reports it. It used to start at 1 (forward) while dir_pin
        # above is created at 0 (reverse), and position moves updated the pin
        # without updating this -- so after homing, whose last coordinated
        # move leaves motor A's pin at reverse, the first positive `vel` on A
        # was judged "already forward" and A ran BACKWARDS until the loop
        # happened to ask for a negative rate. Measured 2026-09-20 on
        # run_124411 (image Jacobian column A inverted, gyro per-motor sign
        # flipped) and run_122343. 0 means UNKNOWN: the first non-zero rate
        # always writes DIR. Every pin write below keeps this in step.
        self._vel_dir = 0
        self._pos_micro = 0                # microsteps * 1e6, dead reckoned
        # Translator phase, in 1/16-step units x 1e6, NEVER reset.
        #
        # The A4988 datasheet requires a step-mode change to happen "at a step
        # position that is common to both step modes", otherwise the internal
        # translator lands on a different state and a step is silently lost.
        # That has to be judged against the DRIVER's phase, which only
        # power-on or reset returns to home -- not against `position`, which
        # `zero`/`dzero` moves to wherever the operator happens to be. Testing
        # a re-zeroable counter makes the alignment check agree with itself
        # and disagree with the hardware.
        self._phase_micro = 0
        self._phase_mult = 1               # 1/16-steps per step at this mode
        # Precomputed so the timer callback never does a dict lookup or a
        # multiply it can avoid -- see vel_tick on why it must not allocate.
        self._invert_dir = bool(config.INVERT_DIR.get(self.name, False))
        self._accel_per_tick = int(getattr(config, "VEL_ACCEL",
                                           config.ACCEL.get(self.name, 20000))
                                   * config.VEL_TICK_MS / 1000)
        if self._accel_per_tick < 1:
            self._accel_per_tick = 1
        self._vel_clock = int(config.VEL_PIO_CLOCK_HZ)
        # Creating the StateMachine switched the STEP pad's function to PIO.
        # Hand it straight back to SIO so the line is a defined, driven LOW
        # while idle -- a floating STEP input can pick up stray pulses.
        self._release_step_pin()

        self.set_microstep(config.DEFAULT_MICROSTEP.get(self.name, 1))

    # ------------------------------------------------------------------
    # STEP pad ownership.  MicroPython sets the pad's FUNCSEL to PIO once,
    # at StateMachine construction.  Nothing re-applies it on sm.active(1),
    # so if we ever hand the pad back to SIO (for single_step, or to park it
    # low) we must explicitly re-claim it before the next PIO move.
    # ------------------------------------------------------------------
    def _claim_step_pin(self):
        funcsel = _FUNCSEL_PIO0 if self.sm_id < 4 else _FUNCSEL_PIO1
        _set_funcsel(self.spec["step"], funcsel)

    def _release_step_pin(self):
        _set_funcsel(self.spec["step"], _FUNCSEL_SIO)
        self.step_pin.init(Pin.OUT)
        self.step_pin.value(0)

    # ------------------------------------------------------------------
    # Driver pad 2 -- nFAULT on a DRV8825, VDD on an A4988 (Finding #2)
    # ------------------------------------------------------------------
    def _init_pad2(self, gpio):
        self.pad2_gpio = gpio
        self.pad2_mode = None
        self.fault_pin = None

        if config.DRIVER_TYPE == "DRV8825":
            # Open-drain, active low.  Pull up so an un-asserted fault reads 1.
            self.fault_pin = Pin(gpio, Pin.IN, Pin.PULL_UP)
            self.pad2_mode = "fault-in"
            return

        src = config.A4988_VDD_SOURCE
        if src == "gpio":
            # Drive it as the chip's logic supply.  Crank the pad's drive
            # strength to 12 mA first so the 3.3 V does not sag under the
            # A4988's VDD draw (~5 mA typ, 10 mA max).
            _set_drive_strength(gpio, 3)
            self.vdd_pin = Pin(gpio, Pin.OUT, value=1)
            self.pad2_mode = "vdd-from-gpio"
            # Let VDD come up and the chip's power-on reset finish before
            # anything drives EN or STEP.  Charging the carrier's 0.1 uF
            # decoupling cap at 12 mA takes ~30 us; the chip's internal POR
            # needs longer, so give it a few milliseconds.
            time.sleep_ms(5)
        elif src == "external":
            # Bodged to 3V3.  Never drive it -- that would be a supply short.
            Pin(gpio, Pin.IN, None)
            self.pad2_mode = "vdd-external"
        else:
            Pin(gpio, Pin.IN, None)
            self.pad2_mode = "off"

    def fault(self):
        """True if the driver is reporting a fault.  None if not observable."""
        if self.fault_pin is None:
            return None
        return self.fault_pin.value() == 0

    # ------------------------------------------------------------------
    # Enable / microstepping
    # ------------------------------------------------------------------
    def enable(self):
        if config.DRIVER_TYPE == "A4988" and self.pad2_mode == "off":
            raise StepperError(
                "%s: A4988 has no logic supply (A4988_VDD_SOURCE='off'). "
                "See HARDWARE_NOTES.md Finding #2." % self.name)
        self.en_pin.value(0)
        self._enabled = True

    def disable(self):
        self.en_pin.value(1)
        self._enabled = False

    @property
    def enabled(self):
        return self._enabled

    def set_microstep(self, div):
        table = MICROSTEP_TABLE[config.DRIVER_TYPE]
        if div not in table:
            raise StepperUsageError(
                "%s does not support 1/%d microstepping (have: %s)"
                % (config.DRIVER_TYPE, div, sorted(table)))
        bits = table[div]
        old_div = self.microstep
        for pin, bit in zip(self.m_pins, bits):
            pin.value(bit)
        self.microstep = div
        self._phase_mult = 16 // div if div <= 16 else 1
        # Rescale the step counters. A microstep change alters what a count
        # MEANS -- 1600 counts is a full turn at 1/8 and half a turn at 1/16 --
        # so leaving them alone silently doubles or halves every angle the
        # firmware reports. This was a latent bug for as long as microstepping
        # was only ever set once at boot; dynamic switching makes it live.
        if old_div and div != old_div:
            self.position = self.position * div // old_div
            self._pos_micro = self._pos_micro * div // old_div
            # Rate is in steps/s, and a step is now a different size, so the
            # same ANGULAR speed needs a proportionally different step rate.
            self.target_rate = self.target_rate * div // old_div
            self.current_rate = self.current_rate * div // old_div
            self._accel_per_tick = max(
                1, int(getattr(config, "VEL_ACCEL",
                               config.ACCEL.get(self.name, 20000))
                       * config.VEL_TICK_MS / 1000) * div // 16)
        # The A4988 needs a moment after a mode change before the next step.
        time.sleep_us(50)
        return bits

    # ------------------------------------------------------------------
    # Velocity mode
    # ------------------------------------------------------------------
    def _period_for(self, rate):
        """PIO Y value for |rate| microsteps/s. 0 means idle."""
        if rate <= 0:
            return 0
        period = int(config.VEL_PIO_CLOCK_HZ / rate)
        y = period - config.VEL_CYCLE_OVERHEAD
        return y if y > 0 else 1

    def _set_period(self, y):
        """
        Push a new period and make it take effect on the NEXT step.

        Not just sm.put(): at a few hundred steps/s the 4-deep TX FIFO fills
        with periods the loop wrote on earlier ticks, and the rate the motor
        actually runs lags the commanded one by up to four steps -- which in a
        tracking loop reads as sloppy, laggy following that no amount of gain
        tuning fixes.

        So: write the word, then immediately pull it into OSR and copy it to X
        from the CPU side. The FIFO is left empty every time, and X is only
        read at the top of a step, so clobbering it mid-hold-loop is harmless.
        """
        sm = self.vel_sm
        sm.put(y)
        sm.exec(_VEL_PULL)
        sm.exec(_VEL_MOV_X_OSR)

    def enter_vel_mode(self):
        if self.mode == "vel":
            # ALREADY IN VELOCITY MODE -- but re-claim the STEP pad anyway.
            #
            # coordinated_move() has no velocity-mode guard (move() and
            # single_step() both do), and its finally clause calls
            # _release_step_pin() on BOTH axes, which hands the pad back to
            # SIO. Returning early here meant the pad was never re-claimed:
            # vel_tick went on writing periods and integrating _pos_micro
            # while not one pulse reached the driver. That is a motor whose
            # counter advances and whose shaft does not move, until reboot --
            # measured on the bench 2026-09-20, tilt only, after a
            # position-mode move on tilt.
            #
            # Claiming an already-claimed pad is a single register write and
            # is harmless, so do it unconditionally rather than trying to
            # guess whether something took it.
            self._claim_step_pin_vel()
            return
        if self.mode == "move":
            raise StepperError("%s: a move is in progress" % self.name)
        if not self._enabled:
            raise StepperUsageError(
                "%s is disabled -- 'enable both' first" % self.name)
        _clear_fifos(self.vel_sm_id)
        self.target_rate = 0
        self.current_rate = 0
        self._pos_micro = 0
        # Belt and braces with the pin-write bookkeeping in _apply_dir /
        # set_direction: on entry the cache is UNKNOWN, so the first non-zero
        # rate writes DIR from a standstill regardless of what any position
        # move, `invert`, or earlier velocity session left behind.
        self._vel_dir = 0
        self._claim_step_pin_vel()
        self.vel_sm.active(1)
        self._set_period(0)              # active but idle
        self.mode = "vel"

    def leave_vel_mode(self):
        if self.mode != "vel":
            return
        self._set_period(0)
        self.target_rate = 0
        self.current_rate = 0
        time.sleep_ms(2)
        self.vel_sm.active(0)
        self._release_step_pin()
        # Fold the dead-reckoned fraction back into the integer counter so
        # move-mode position picks up where velocity mode left off.
        self.position += self._pos_micro // 1000000
        self._pos_micro = 0          # phase deliberately survives: it tracks
                                     # the driver, not our datum
        self.mode = "idle"

    def _claim_step_pin_vel(self):
        funcsel = _FUNCSEL_PIO0 if self.vel_sm_id < 4 else _FUNCSEL_PIO1
        _set_funcsel(self.spec["step"], funcsel)

    def set_target_rate(self, rate):
        """Commanded signed rate in microsteps/s. Clamped, not rejected."""
        lim = config.VEL_MAX_RATE
        if rate > lim:
            rate = lim
        elif rate < -lim:
            rate = -lim
        self.target_rate = int(rate)

    def vel_tick(self, dt_us):
        """
        One control tick. Runs in interrupt context: MUST NOT ALLOCATE.

        Integer arithmetic throughout, because MicroPython heap-allocates
        floats on this port and the allocator is unavailable inside an ISR.
        Rates are microsteps/s as ints and position is accumulated in
        microsteps * 1e6 so a 5 ms tick at a few hundred steps/s still carries
        exactly, with no float and no drift.

        The first version of this used floats and `for ax in self.axes.values()`
        -- a dict view plus an iterator, 200 times a second. It ran the board
        out of heap inside the ISR, USB CDC stopped being serviced, and the
        console wedged hard enough to need a power cycle. The motors were safe
        (the watchdog had already zeroed them) but nothing else was.
        """
        tr = self.target_rate
        cr = self.current_rate
        if cr != tr:
            step = self._accel_per_tick
            d = tr - cr
            if d > step:
                cr += step
            elif d < -step:
                cr -= step
            else:
                cr = tr

        # DIR is latched on the step edge, so a reversal must happen at a
        # standstill or the step is lost silently.
        if cr > 0:
            want = 1
        elif cr < 0:
            want = -1
        else:
            want = self._vel_dir
        if want != self._vel_dir:
            self._set_period(0)
            time.sleep_us(300)
            self._apply_dir(want > 0)
            self._vel_dir = want

        self.current_rate = cr
        mag = cr if cr >= 0 else -cr
        if mag:
            period = self._vel_clock // mag
            y = period - config.VEL_CYCLE_OVERHEAD
            if y < 1:
                y = 1
        else:
            y = 0
        self._set_period(y)
        # micro-steps scaled by 1e6; dt_us is an int, so this stays integral.
        d = cr * dt_us
        self._pos_micro += d
        self._phase_micro += d * self._phase_mult

    @property
    def vel_position(self):
        """Dead-reckoned position while in velocity mode."""
        return self.position + self._pos_micro // 1000000

    @property
    def phase16(self):
        """Driver translator phase in 1/16-step units. Never re-zeroed."""
        return self._phase_micro // 1000000

    def _apply_dir(self, forward):
        """Direction pin only, no allocation -- safe from the timer ISR."""
        level = 1 if forward else 0
        if self._invert_dir:
            level ^= 1
        self.dir_pin.value(level)
        self._vel_dir = 1 if forward else -1      # small int: no allocation

    def set_direction(self, forward):
        level = 1 if forward else 0
        if config.INVERT_DIR.get(self.name, False):
            level ^= 1
        self.dir_pin.value(level)
        # Keep the velocity-mode cache honest: this is the write that used to
        # desynchronise it (see __init__ on _vel_dir).
        self._vel_dir = 1 if forward else -1
        # A4988 DIR setup time before a STEP rising edge is 200 ns; be generous.
        time.sleep_us(5)
        return level

    # ------------------------------------------------------------------
    # Units
    # ------------------------------------------------------------------
    def steps_per_rev(self):
        return (config.FULL_STEPS_PER_REV * self.microstep
                * config.GEAR_RATIO.get(self.name, 1.0))

    def degrees_to_steps(self, deg):
        return int(round(deg * self.steps_per_rev() / 360.0))

    def steps_to_degrees(self, steps):
        return steps * 360.0 / self.steps_per_rev()

    # ------------------------------------------------------------------
    # Motion
    # ------------------------------------------------------------------
    def abort(self):
        self._abort = True

    def _delay_word(self, rate):
        """Convert microsteps/sec into a PIO delay word."""
        rate = max(1.0, min(float(rate), config.ABSOLUTE_MAX_RATE))
        period_cycles = int(round(config.PIO_CLOCK_HZ / rate))
        word = period_cycles - _PIO_OVERHEAD_CYCLES
        if word < 0:
            word = 0
        return word

    def actual_rate(self, requested):
        """The rate you really get after PIO quantisation."""
        word = self._delay_word(requested)
        return config.PIO_CLOCK_HZ / float(word + _PIO_OVERHEAD_CYCLES)

    def move(self, steps, rate=None, accel=None, start_rate=None,
             on_progress=None, guard=None, gc_collect=None):
        """
        Move `steps` microsteps (sign = direction) with a trapezoidal ramp.

        guard      -- callable returning True to stop immediately (endstops).
        on_progress-- callable(done, total) invoked every ~64 steps.
        gc_collect -- None (default) collects only for moves of at least
                      _GC_THRESHOLD_STEPS.  Pass True/False to force it.
                      Timing measurements need this pinned, because a
                      collect that happens on one move and not another
                      adds ~1.7 ms of overhead to just one of them.

        Returns a dict describing what actually happened.
        """
        if steps == 0:
            return {"steps": 0, "aborted": False, "guarded": False,
                    "elapsed_us": 0}
        if not self._enabled:
            raise StepperError("%s is not enabled -- call enable() first"
                               % self.name)
        # Two step generators share one STEP pin. Letting a move start while
        # the velocity SM is driving it would have both writing the same pad,
        # and the result is not "both move" but a garbled pulse train that
        # loses steps without reporting anything.
        if self.mode == "vel":
            # USAGE, NOT A FAULT. cli.py answers a plain StepperError by
            # calling safe_state(), which de-energises BOTH axes -- and on a
            # tilt axis with gravity on it that drops the barrel. Asking for a
            # move at the wrong moment is a mistake to report, not a reason to
            # let go. Measured 2026-09-20: every refusal came back
            # "[everything disabled]" with the payload held at -37.7 deg.
            raise StepperUsageError(
                "%s is in velocity mode -- 'velmode off' before moving"
                % self.name)

        forward = steps > 0
        total = abs(int(steps))
        self.set_direction(forward)

        v_max = float(rate if rate is not None
                      else config.MAX_RATE.get(self.name, 2000))
        v_min = float(start_rate if start_rate is not None
                      else config.START_RATE.get(self.name, 200))
        a = float(accel if accel is not None
                  else config.ACCEL.get(self.name, 20000))

        v_max = max(1.0, min(v_max, config.ABSOLUTE_MAX_RATE))
        v_min = max(1.0, min(v_min, v_max))

        # Steps needed to reach v_max from v_min under constant accel:
        #   v^2 = v0^2 + 2*a*n  ->  n = (v_max^2 - v_min^2) / (2a)
        if a > 0:
            ramp_n = int((v_max * v_max - v_min * v_min) / (2.0 * a))
        else:
            ramp_n = 0
        ramp_n = max(0, ramp_n)

        # If the move is too short to reach v_max, use a triangular profile.
        if 2 * ramp_n > total:
            ramp_n = total // 2

        cruise_n = total - 2 * ramp_n

        self._abort = False
        sm = self.sm
        sm.active(0)
        _clear_fifos(self.sm_id)   # drop anything left by an aborted move
        sm.restart()
        self._claim_step_pin()
        sm.active(1)

        # The FIFO is only 4 deep; an underrun just stretches one step, which
        # is harmless, but a GC pause mid-ramp is ugly.  Collect up front --
        # only for moves long enough to be at risk, since gc.collect() costs
        # ~1.7 ms on this heap and would otherwise dominate short moves.
        if gc_collect is None:
            gc_collect = total >= _GC_THRESHOLD_STEPS
        if gc_collect:
            gc.collect()

        done = 0
        t0 = time.ticks_us()
        guarded = False
        try:
            # ---- accelerate ----
            v = v_min
            two_a = 2.0 * a
            vmin_sq = v_min * v_min
            for n in range(ramp_n):
                v = (vmin_sq + two_a * n) ** 0.5
                sm.put(self._delay_word(v))
                done += 1
                if (done & 63) == 0:
                    reason = self._check_stop(guard, on_progress, done, total)
                    if reason:
                        guarded = (reason == "guard")
                        raise _Stop()

            # ---- cruise ----
            word = self._delay_word(v_max if ramp_n else v_min)
            for _ in range(cruise_n):
                sm.put(word)
                done += 1
                if (done & 63) == 0:
                    reason = self._check_stop(guard, on_progress, done, total)
                    if reason:
                        guarded = (reason == "guard")
                        raise _Stop()

            # ---- decelerate ----
            for n in range(ramp_n):
                v = (vmin_sq + two_a * (ramp_n - 1 - n)) ** 0.5
                sm.put(self._delay_word(v))
                done += 1
                if (done & 63) == 0:
                    reason = self._check_stop(guard, on_progress, done, total)
                    if reason:
                        guarded = (reason == "guard")
                        raise _Stop()

            # Let the FIFO drain so `done` reflects pulses actually emitted.
            # With autopull on, the SM stalls at `out` once the FIFO is empty,
            # so this terminates cleanly.
            while sm.tx_fifo() > 0:
                if guard is not None and guard():
                    guarded = True
                    break
            # One word may still be in the OSR mid-execution.  Both profiles
            # finish at v_min -- a full ramp decelerates back down to it, and
            # an accel=0 move cruises at it -- so wait out that period rather
            # than a fixed guess, or the elapsed time comes out short at low
            # rates and the timing test reports a phantom error.
            tail_us = ((self._delay_word(v_min) + _PIO_OVERHEAD_CYCLES)
                       * 1000000 // config.PIO_CLOCK_HZ)
            time.sleep_us(min(tail_us + 50, 50000))

        except _Stop:
            pass
        finally:
            sm.active(0)
            # Read the FIFO depth BEFORE clearing it -- words still queued
            # were never turned into pulses.
            leftover = sm.tx_fifo()
            _clear_fifos(self.sm_id)
            self._release_step_pin()
            # Update position HERE, not after the try, so it stays correct
            # even when the move dies by exception -- a Ctrl-C e-stop raises
            # KeyboardInterrupt straight through this frame, and if the
            # position update sat below the try/finally it would be skipped,
            # silently desynchronising the axis from reality at exactly the
            # moment you most need to trust it.
            emitted = done - leftover
            self.position += emitted if forward else -emitted
            # Phase follows every real pulse, in either mode.
            self._phase_micro += ((emitted if forward else -emitted)
                                  * self._phase_mult * 1000000)

        elapsed = time.ticks_diff(time.ticks_us(), t0)

        result = {
            "steps": emitted if forward else -emitted,
            "requested": steps,
            "aborted": self._abort,
            "guarded": guarded,
            "elapsed_us": elapsed,
            "ramp_steps": ramp_n,
            "cruise_steps": cruise_n,
            "peak_rate": v_max if ramp_n else v_min,
            "position": self.position,
        }
        self._last_move = result
        if on_progress:
            on_progress(done, total)
        return result

    def _check_stop(self, guard, on_progress, done, total):
        """Return None to keep going, else 'abort' or 'guard'."""
        if on_progress:
            on_progress(done, total)
        if self._abort:
            return "abort"
        if guard is not None and guard():
            return "guard"
        return None

    def move_degrees(self, deg, **kw):
        return self.move(self.degrees_to_steps(deg), **kw)

    def single_step(self, forward=True, high_us=10, low_us=10000):
        """One bit-banged pulse.  For scoping and for slow visual checks."""
        if not self._enabled:
            raise StepperError("%s is not enabled" % self.name)
        if self.mode == "vel":
            raise StepperError(
                "%s is in velocity mode -- 'velmode off' first" % self.name)
        self._release_step_pin()       # make sure SIO owns the pad
        self.set_direction(forward)
        self.step_pin.value(1)
        time.sleep_us(high_us)
        self.step_pin.value(0)
        time.sleep_us(low_us)
        self.position += 1 if forward else -1
        self._phase_micro += ((1 if forward else -1)
                              * self._phase_mult * 1000000)
        return self.position

    def zero(self):
        self.position = 0

    def status(self):
        f = self.fault()
        return {
            "name": self.name,
            "ref": self.ref,
            "enabled": self._enabled,
            "microstep": self.microstep,
            "position": self.position,
            "degrees": round(self.steps_to_degrees(self.position), 3),
            "steps_per_rev": self.steps_per_rev(),
            "pad2_mode": self.pad2_mode,
            "fault": f,
            "dir_level": self.dir_pin.value(),
        }


class _Stop(Exception):
    pass


def _set_drive_strength(gpio, level):
    """PADS_BANK0 DRIVE field: 0=2mA 1=4mA 2=8mA 3=12mA."""
    try:
        PADS_BANK0 = 0x4001C000
        addr = PADS_BANK0 + 0x04 + 4 * gpio
        val = machine.mem32[addr]
        val = (val & ~(0x3 << 4)) | ((level & 0x3) << 4)
        machine.mem32[addr] = val
        return True
    except Exception:
        return False


# --------------------------------------------------------------------------
# Direct RP2040 register pokes.  MicroPython's rp2 module does not expose
# either of these operations, and both are needed for correct behaviour:
#   * FUNCSEL, so the STEP pad can be handed between PIO and SIO
#   * FIFO clear, so an aborted move does not leak queued steps into the next
# --------------------------------------------------------------------------
_IO_BANK0 = 0x40014000
_FUNCSEL_SIO = 5
_FUNCSEL_PIO0 = 6
_FUNCSEL_PIO1 = 7

_PIO_BASE = (0x50200000, 0x50300000)
_SM0_SHIFTCTRL = 0x0D0
_SM_STRIDE = 0x18
_FJOIN_RX_BIT = 1 << 31


def _set_funcsel(gpio, funcsel):
    try:
        addr = _IO_BANK0 + 0x04 + 8 * gpio        # GPIOn_CTRL
        val = machine.mem32[addr]
        machine.mem32[addr] = (val & ~0x1F) | (funcsel & 0x1F)
        return True
    except Exception:
        return False


def _get_funcsel(gpio):
    """Read a pad's current function select. None if it cannot be read.

    5 == SIO, 6 == PIO0, 7 == PIO1 (the constants above). This exists so the
    `pads` diagnostic can answer, in one command, "is the velocity state
    machine actually connected to the STEP pin?" -- the question that cost an
    evening when an axis counted steps it was not emitting.
    """
    try:
        return machine.mem32[_IO_BANK0 + 0x04 + 8 * gpio] & 0x1F
    except Exception:
        return None


def _clear_fifos(sm_id):
    """Equivalent of the SDK's pio_sm_clear_fifos(): toggle FJOIN_RX twice."""
    try:
        base = _PIO_BASE[0 if sm_id < 4 else 1]
        addr = base + _SM0_SHIFTCTRL + (sm_id % 4) * _SM_STRIDE
        machine.mem32[addr] = machine.mem32[addr] ^ _FJOIN_RX_BIT
        machine.mem32[addr] = machine.mem32[addr] ^ _FJOIN_RX_BIT
        return True
    except Exception:
        return False


